/* net.c - SovereignChain networking (Phase 3: Ed25519 authenticated TCP).
 *
 * DESIGN OVERVIEW
 * ---------------
 * Every peer connection goes through a 3-message handshake before any
 * application messages are accepted. The handshake lives inside a
 * pending_conn_t until it completes, then the connection is promoted to
 * an authenticated peer_conn_t.
 *
 * Peer state machine:
 *   PEER_DISCONNECTED  → start_connect()       → PEER_CONNECTING
 *   PEER_CONNECTING    → POLLOUT (SO_ERROR==0)  → PEER_HS_INIT_SENT
 *                        (we send HELLO_INIT immediately on connect)
 *   PEER_HS_INIT_SENT  → recv HELLO_CHAL        → PEER_HS_RESP_SENT
 *   PEER_HS_RESP_SENT  → recv HELLO_CHAL_ACK    → PEER_CONNECTED
 *
 * Inbound side (pending_conn_t):
 *   Accept → wait for HELLO_INIT → verify & send HELLO_CHAL → wait for
 *   HELLO_RESP → verify → promote to peer_conn_t slot.
 *
 * Validator enforcement: only messages whose sender has a pubkey that
 * matches network.conf are accepted. The handshake is the moment of
 * enforcement — we compare the presented pubkey against the pinned value.
 */
#define _POSIX_C_SOURCE 200809L

#include "net.h"

#include <arpa/inet.h>
#include <errno.h>
#include <fcntl.h>
#include <netinet/in.h>
#include <poll.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/socket.h>
#include <time.h>
#include <unistd.h>

#include "log.h"

#define RECONNECT_INTERVAL_MS 1000
#define MAX_PENDING_INBOUND   8
#define BUF_SIZE              (SC_NET_HEADER_LEN + SC_NET_MAX_PAYLOAD)

/* ------------------------------------------------------------------ */
/* Peer state machine                                                  */
/* ------------------------------------------------------------------ */

typedef enum {
    PEER_DISCONNECTED = 0,
    PEER_CONNECTING,       /* TCP SYN sent, waiting for POLLOUT         */
    PEER_HS_INIT_SENT,     /* HELLO_INIT sent, waiting for HELLO_CHAL   */
    PEER_HS_RESP_SENT,     /* HELLO_RESP sent, waiting for acceptance   */
    PEER_CONNECTED         /* Handshake complete, application traffic OK */
} peer_state_t;

typedef struct {
    int          node_id;
    char         host[SC_MAX_HOST];
    uint16_t     port;
    bool         is_target;       /* true = we initiate connection to them */
    peer_state_t state;
    int          fd;
    int64_t      next_reconnect_ms;

    /* Nonce we generated (outbound) or received (inbound); used to verify
     * the peer's HELLO_RESP signature. */
    uint8_t      handshake_nonce[SC_NONCE_LEN];

    uint8_t      in_buf[BUF_SIZE];
    size_t       in_len;

    uint8_t      out_buf[BUF_SIZE];
    size_t       out_len;
} peer_conn_t;

/* Inbound handshake state: one per pending accept()'d connection.
 * Promoted into a peer_conn_t slot once HELLO_RESP verifies. */
typedef enum {
    PEND_WAIT_INIT = 0,  /* waiting for HELLO_INIT from connector  */
    PEND_WAIT_RESP       /* HELLO_CHAL sent, waiting for HELLO_RESP */
} pend_hs_state_t;

typedef struct {
    int             fd;
    pend_hs_state_t hs_state;
    int             claimed_id;                   /* from HELLO_INIT */
    uint8_t         nonce[SC_NONCE_LEN];          /* generated by us */
    uint8_t         in_buf[BUF_SIZE];
    size_t          in_len;
    uint8_t         out_buf[BUF_SIZE];
    size_t          out_len;
} pending_conn_t;

struct sc_net {
    const node_info_t    *me;
    const sc_keypair_t   *my_keypair;   /* our signing key; not owned */
    const network_config_t *topology;   /* for pinned pubkey lookup    */
    int                   listen_fd;
    sc_net_msg_cb         msg_cb;
    void                 *user_data;

    peer_conn_t           peers[SC_MAX_NODES];
    size_t                peer_count;

    pending_conn_t        pending[MAX_PENDING_INBOUND];
};

/* ------------------------------------------------------------------ */
/* Helpers                                                             */
/* ------------------------------------------------------------------ */

static int64_t get_now_ms(void)
{
    struct timespec ts;
    if (clock_gettime(CLOCK_MONOTONIC, &ts) != 0)
        return 0;
    return ((int64_t)ts.tv_sec * 1000) + (ts.tv_nsec / 1000000L);
}

static sc_err_t set_nonblocking(int fd)
{
    int flags = fcntl(fd, F_GETFL, 0);
    if (flags < 0)
        return SC_ERR_IO;
    if (fcntl(fd, F_SETFL, flags | O_NONBLOCK) < 0)
        return SC_ERR_IO;
    return SC_OK;
}

static peer_conn_t *find_peer_by_id(sc_net_t *net, int id)
{
    for (size_t i = 0; i < net->peer_count; i++) {
        if (net->peers[i].node_id == id)
            return &net->peers[i];
    }
    return NULL;
}

static void close_peer(sc_net_t *net, peer_conn_t *p, const char *reason)
{
    (void)net;
    if (p->fd >= 0) {
        log_eventf(LOG_INFO, "net", "peer_disconnected",
                   "peer=%d reason=\"%s\"", p->node_id, reason ? reason : "closed");
        close(p->fd);
        p->fd = -1;
    }
    p->state  = PEER_DISCONNECTED;
    p->in_len = 0;
    p->out_len = 0;
    p->next_reconnect_ms = get_now_ms() + RECONNECT_INTERVAL_MS;
}

static void close_pending(pending_conn_t *pend)
{
    if (pend->fd >= 0) {
        close(pend->fd);
        pend->fd = -1;
    }
    pend->in_len  = 0;
    pend->out_len = 0;
    pend->hs_state = PEND_WAIT_INIT;
}

/* ------------------------------------------------------------------ */
/* Frame helpers — write header+payload into a flat byte buffer.       */
/*                                                                     */
/* WHY memcpy instead of struct cast?                                  */
/* Network protocols use big-endian (network byte order). On x86 the   */
/* CPU is little-endian, so multi-byte integers must be byte-swapped.  */
/* htonl/htons do that swap. We then memcpy into the buffer because    */
/* casting a char* to a uint32_t* and assigning violates strict        */
/* aliasing rules (UB in C), and memcpy is always safe.                */
/* ------------------------------------------------------------------ */

static bool enqueue_frame_to(uint8_t *out_buf, size_t *out_len,
                             size_t buf_cap,
                             uint16_t type, const void *payload, size_t len)
{
    if (len > SC_NET_MAX_PAYLOAD)
        return false;
    size_t total = SC_NET_HEADER_LEN + len;
    if (buf_cap - *out_len < total)
        return false;

    uint32_t net_len  = htonl((uint32_t)len);
    uint16_t net_type = htons(type);
    uint16_t net_res  = 0;

    uint8_t *dest = out_buf + *out_len;
    memcpy(dest,     &net_len,  4);
    memcpy(dest + 4, &net_type, 2);
    memcpy(dest + 6, &net_res,  2);
    if (len > 0 && payload)
        memcpy(dest + SC_NET_HEADER_LEN, payload, len);

    *out_len += total;
    return true;
}

static bool enqueue_to_peer(peer_conn_t *p, uint16_t type,
                            const void *payload, size_t len)
{
    if (!enqueue_frame_to(p->out_buf, &p->out_len, sizeof(p->out_buf),
                          type, payload, len)) {
        log_eventf(LOG_WARN, "net", "out_buf_full",
                   "peer=%d dropping msg type=%u", p->node_id, (unsigned)type);
        return false;
    }
    return true;
}

static bool enqueue_to_pending(pending_conn_t *pend, uint16_t type,
                               const void *payload, size_t len)
{
    return enqueue_frame_to(pend->out_buf, &pend->out_len,
                            sizeof(pend->out_buf), type, payload, len);
}

/* Flush as much of out_buf as the socket will accept. Returns false on error. */
static bool flush_pending_out(int fd, uint8_t *out_buf, size_t *out_len)
{
    if (*out_len == 0)
        return true;
    ssize_t sent = send(fd, out_buf, *out_len, 0);
    if (sent > 0) {
        size_t rem = *out_len - (size_t)sent;
        if (rem > 0)
            memmove(out_buf, out_buf + sent, rem);
        *out_len = rem;
        return true;
    }
    if (sent < 0 && (errno == EAGAIN || errno == EWOULDBLOCK || errno == EINTR))
        return true;
    return false; /* real error */
}

/* ------------------------------------------------------------------ */
/* Pinned pubkey lookup: get the pubkey pinned for node_id in          */
/* network.conf, or return NULL if the node has no pinned key.         */
/* ------------------------------------------------------------------ */

static const uint8_t *pinned_pubkey(const sc_net_t *net, int node_id)
{
    const node_info_t *ni = config_find_node(net->topology, node_id);
    if (!ni || !ni->has_pubkey)
        return NULL;
    return ni->pubkey;
}

/* ------------------------------------------------------------------ */
/* OUTBOUND HANDSHAKE (we connected to them)                           */
/*                                                                     */
/* Step 1: send HELLO_INIT right after TCP connect.                    */
/* Payload: sender_id(4) | our_pubkey(32)                              */
/* ------------------------------------------------------------------ */

static void send_hello_init(sc_net_t *net, peer_conn_t *p)
{
    uint8_t buf[SC_HELLO_INIT_LEN];
    uint8_t my_pubkey[SC_ED25519_PUBKEY_LEN];

    if (crypto_get_pubkey(net->my_keypair, my_pubkey) != SC_OK) {
        log_event(LOG_ERROR, "net", "hs_init_pubkey_failed");
        close_peer(net, p, "cannot get own pubkey");
        return;
    }

    uint32_t my_id_net = htonl((uint32_t)net->me->id);
    memcpy(buf,     &my_id_net, 4);
    memcpy(buf + 4, my_pubkey, SC_ED25519_PUBKEY_LEN);

    if (!enqueue_to_peer(p, MSG_TYPE_HELLO_INIT, buf, sizeof(buf))) {
        close_peer(net, p, "hello_init enqueue failed");
        return;
    }
    p->state = PEER_HS_INIT_SENT;
    log_eventf(LOG_DEBUG, "net", "hs_init_sent", "peer=%d", p->node_id);
}

/* ------------------------------------------------------------------ */
/* Step 2b: we (outbound) received HELLO_CHAL — verify their sig,     */
/* generate HELLO_RESP (sign nonce with our key).                      */
/*                                                                     */
/* HELLO_CHAL payload: nonce(32) | peer_pubkey(32) | sig(64)           */
/* HELLO_RESP payload: sig_of_nonce(64)                                */
/* ------------------------------------------------------------------ */

static void handle_hello_chal(sc_net_t *net, peer_conn_t *p,
                              const uint8_t *payload, size_t len)
{
    if (len != SC_HELLO_CHAL_LEN) {
        close_peer(net, p, "bad HELLO_CHAL length");
        return;
    }
    const uint8_t *nonce       = payload;
    const uint8_t *peer_pubkey = payload + SC_NONCE_LEN;
    const uint8_t *peer_sig    = payload + SC_NONCE_LEN + SC_ED25519_PUBKEY_LEN;

    /* 1. Check peer's presented pubkey against the one pinned for their node_id. */
    const uint8_t *pinned = pinned_pubkey(net, p->node_id);
    if (!pinned) {
        log_eventf(LOG_WARN, "net", "hs_no_pinned_key",
                   "peer=%d — rejecting (no pubkey in network.conf)", p->node_id);
        close_peer(net, p, "no pinned pubkey");
        return;
    }
    if (memcmp(peer_pubkey, pinned, SC_ED25519_PUBKEY_LEN) != 0) {
        log_eventf(LOG_WARN, "net", "hs_pubkey_mismatch",
                   "peer=%d — key does not match network.conf", p->node_id);
        close_peer(net, p, "pubkey mismatch");
        return;
    }

    /* 2. Verify peer's signature of the nonce.
     *    They signed the nonce with their private key; we verify with
     *    the public key they just presented (which we confirmed = pinned). */
    sc_keypair_t *peer_kp = NULL;
    if (crypto_pubkey_from_raw(&peer_kp, peer_pubkey) != SC_OK) {
        close_peer(net, p, "cannot build peer pubkey handle");
        return;
    }
    sc_err_t vrc = crypto_verify(peer_kp, nonce, SC_NONCE_LEN, peer_sig);
    crypto_keypair_free(peer_kp);

    if (vrc != SC_OK) {
        log_eventf(LOG_WARN, "net", "hs_chal_sig_bad", "peer=%d", p->node_id);
        close_peer(net, p, "HELLO_CHAL signature invalid");
        return;
    }

    /* 3. Save nonce so we can verify any follow-up from inbound direction. */
    memcpy(p->handshake_nonce, nonce, SC_NONCE_LEN);

    /* 4. Sign the nonce with OUR private key and send HELLO_RESP. */
    uint8_t my_sig[SC_ED25519_SIG_LEN];
    if (crypto_sign(net->my_keypair, nonce, SC_NONCE_LEN, my_sig) != SC_OK) {
        close_peer(net, p, "HELLO_RESP sign failed");
        return;
    }
    if (!enqueue_to_peer(p, MSG_TYPE_HELLO_RESP, my_sig, SC_ED25519_SIG_LEN)) {
        close_peer(net, p, "HELLO_RESP enqueue failed");
        return;
    }

    /* Outbound connector considers handshake done after sending RESP.
     * Listener verifies in handle_hello_resp. We trust that TCP delivers
     * our RESP; if it's bad the listener will close the socket. */
    p->state = PEER_CONNECTED;
    log_eventf(LOG_INFO, "net", "peer_authenticated",
               "peer=%d dir=outbound", p->node_id);
}

/* ------------------------------------------------------------------ */
/* INBOUND HANDSHAKE (they connected to us) — lives in pending_conn_t  */
/*                                                                     */
/* Step 2a: received HELLO_INIT, send HELLO_CHAL.                      */
/* ------------------------------------------------------------------ */

static void handle_pending_hello_init(sc_net_t *net, pending_conn_t *pend,
                                      const uint8_t *payload, size_t len)
{
    if (len != SC_HELLO_INIT_LEN) {
        log_event(LOG_WARN, "net", "pend_bad_init_len");
        close_pending(pend);
        return;
    }
    uint32_t sender_id_net;
    memcpy(&sender_id_net, payload, 4);
    int sender_id = (int)ntohl(sender_id_net);
    const uint8_t *presented_pubkey = payload + 4;

    /* Verify the presented pubkey matches what's pinned for that node_id. */
    const uint8_t *pinned = pinned_pubkey(net, sender_id);
    if (!pinned) {
        log_eventf(LOG_WARN, "net", "pend_no_pinned_key", "node=%d", sender_id);
        close_pending(pend);
        return;
    }
    if (memcmp(presented_pubkey, pinned, SC_ED25519_PUBKEY_LEN) != 0) {
        log_eventf(LOG_WARN, "net", "pend_pubkey_mismatch", "node=%d", sender_id);
        close_pending(pend);
        return;
    }

    /* Make sure there's a peer slot for this sender. */
    peer_conn_t *p = find_peer_by_id(net, sender_id);
    if (!p) {
        log_eventf(LOG_WARN, "net", "pend_unknown_sender", "node=%d", sender_id);
        close_pending(pend);
        return;
    }

    pend->claimed_id = sender_id;
    pend->hs_state   = PEND_WAIT_RESP;

    /* Generate a fresh 32-byte random nonce.
     * The nonce is the security heart of the handshake: it's unique per
     * connection, so the connector must sign THIS nonce with THIS private
     * key, right now. It prevents replay attacks where an attacker
     * captures a HELLO_RESP from a past session and replays it. */
    if (crypto_rand_bytes(pend->nonce, SC_NONCE_LEN) != SC_OK) {
        log_event(LOG_ERROR, "net", "pend_nonce_gen_failed");
        close_pending(pend);
        return;
    }

    /* Build HELLO_CHAL: nonce(32) | our_pubkey(32) | sig(nonce)(64) */
    uint8_t my_pubkey[SC_ED25519_PUBKEY_LEN];
    uint8_t my_sig[SC_ED25519_SIG_LEN];
    if (crypto_get_pubkey(net->my_keypair, my_pubkey) != SC_OK ||
        crypto_sign(net->my_keypair, pend->nonce, SC_NONCE_LEN, my_sig) != SC_OK) {
        log_event(LOG_ERROR, "net", "pend_chal_sign_failed");
        close_pending(pend);
        return;
    }

    uint8_t chal[SC_HELLO_CHAL_LEN];
    memcpy(chal,                                          pend->nonce,  SC_NONCE_LEN);
    memcpy(chal + SC_NONCE_LEN,                           my_pubkey,   SC_ED25519_PUBKEY_LEN);
    memcpy(chal + SC_NONCE_LEN + SC_ED25519_PUBKEY_LEN,  my_sig,      SC_ED25519_SIG_LEN);

    if (!enqueue_to_pending(pend, MSG_TYPE_HELLO_CHAL, chal, sizeof(chal))) {
        log_event(LOG_WARN, "net", "pend_chal_enqueue_failed");
        close_pending(pend);
        return;
    }
    log_eventf(LOG_DEBUG, "net", "hs_chal_sent", "to=%d", sender_id);
}

/* Step 3 (inbound): received HELLO_RESP — verify connector's sig,
 * then promote pending → authenticated peer. */
static void handle_pending_hello_resp(sc_net_t *net, pending_conn_t *pend,
                                      const uint8_t *payload, size_t len)
{
    if (len != SC_HELLO_RESP_LEN) {
        log_event(LOG_WARN, "net", "pend_bad_resp_len");
        close_pending(pend);
        return;
    }
    const uint8_t *resp_sig = payload;

    /* Verify the connector signed OUR nonce with their private key. */
    const uint8_t *pinned = pinned_pubkey(net, pend->claimed_id);
    if (!pinned) {
        close_pending(pend);
        return;
    }
    sc_keypair_t *peer_kp = NULL;
    if (crypto_pubkey_from_raw(&peer_kp, pinned) != SC_OK) {
        close_pending(pend);
        return;
    }
    sc_err_t vrc = crypto_verify(peer_kp, pend->nonce, SC_NONCE_LEN, resp_sig);
    crypto_keypair_free(peer_kp);

    if (vrc != SC_OK) {
        log_eventf(LOG_WARN, "net", "pend_resp_sig_bad",
                   "node=%d — rejecting impostor", pend->claimed_id);
        close_pending(pend);
        return;
    }

    /* ✅ Handshake complete — promote to authenticated peer slot. */
    peer_conn_t *p = find_peer_by_id(net, pend->claimed_id);
    if (!p) {
        close_pending(pend);
        return;
    }
    if (p->fd >= 0)
        close_peer(net, p, "replaced by new inbound");

    p->fd     = pend->fd;
    p->state  = PEER_CONNECTED;
    p->in_len = 0;
    p->out_len = 0;

    /* Transfer any bytes already in the pending buffer beyond the HELLO_RESP frame. */
    /* (handled by caller after draining) */

    pend->fd     = -1;  /* ownership transferred */
    pend->in_len = 0;
    pend->out_len = 0;
    pend->hs_state = PEND_WAIT_INIT;

    log_eventf(LOG_INFO, "net", "peer_authenticated",
               "peer=%d dir=inbound", p->node_id);
}

/* ------------------------------------------------------------------ */
/* Application frame processing (post-handshake)                       */
/* ------------------------------------------------------------------ */

static void process_frame(sc_net_t *net, int from_id, uint16_t type,
                          const uint8_t *payload, size_t len)
{
    if (type == MSG_TYPE_PING) {
        net_send(net, from_id, MSG_TYPE_PONG, payload, len);
    } else {
        if (net->msg_cb)
            net->msg_cb(from_id, type, payload, len, net->user_data);
    }
}

/* Consume complete frames from a peer's in_buf. */
static void drain_peer_in_buf(sc_net_t *net, peer_conn_t *p)
{
    while (p->in_len >= SC_NET_HEADER_LEN) {
        uint32_t net_len;
        uint16_t net_type;
        memcpy(&net_len,  p->in_buf,     4);
        memcpy(&net_type, p->in_buf + 4, 2);

        uint32_t payload_len = ntohl(net_len);
        uint16_t type        = ntohs(net_type);

        if (payload_len > SC_NET_MAX_PAYLOAD) {
            log_eventf(LOG_ERROR, "net", "frame_oversized",
                       "peer=%d len=%u", p->node_id, payload_len);
            close_peer(net, p, "oversized frame");
            return;
        }
        size_t total = SC_NET_HEADER_LEN + payload_len;
        if (p->in_len < total)
            break; /* wait for more data */

        process_frame(net, p->node_id, type, p->in_buf + SC_NET_HEADER_LEN, payload_len);

        size_t remaining = p->in_len - total;
        if (remaining > 0)
            memmove(p->in_buf, p->in_buf + total, remaining);
        p->in_len = remaining;
    }
}

/* Consume frames from a pending connection's in_buf based on hs_state. */
static void drain_pending_in_buf(sc_net_t *net, pending_conn_t *pend)
{
    while (pend->in_len >= SC_NET_HEADER_LEN) {
        uint32_t net_len;
        uint16_t net_type;
        memcpy(&net_len,  pend->in_buf,     4);
        memcpy(&net_type, pend->in_buf + 4, 2);

        uint32_t payload_len = ntohl(net_len);
        uint16_t type        = ntohs(net_type);

        if (payload_len > SC_NET_MAX_PAYLOAD) {
            close_pending(pend);
            return;
        }
        size_t total = SC_NET_HEADER_LEN + payload_len;
        if (pend->in_len < total)
            break;

        const uint8_t *payload = pend->in_buf + SC_NET_HEADER_LEN;

        if (pend->hs_state == PEND_WAIT_INIT && type == MSG_TYPE_HELLO_INIT) {
            handle_pending_hello_init(net, pend, payload, payload_len);
        } else if (pend->hs_state == PEND_WAIT_RESP && type == MSG_TYPE_HELLO_RESP) {
            handle_pending_hello_resp(net, pend, payload, payload_len);
            /* After promotion pend->fd == -1, stop processing. */
            if (pend->fd < 0)
                return;
        } else {
            /* Wrong message type for this handshake state — reject. */
            log_eventf(LOG_WARN, "net", "pend_unexpected_msg",
                       "type=%u hs_state=%d", (unsigned)type, pend->hs_state);
            close_pending(pend);
            return;
        }

        size_t remaining = pend->in_len - total;
        if (remaining > 0)
            memmove(pend->in_buf, pend->in_buf + total, remaining);
        pend->in_len = remaining;
    }
}

/* ------------------------------------------------------------------ */
/* Outbound connect                                                     */
/* ------------------------------------------------------------------ */

static void start_connect(sc_net_t *net, peer_conn_t *p)
{
    struct sockaddr_in sa;
    int fd = socket(AF_INET, SOCK_STREAM, 0);
    if (fd < 0) {
        p->next_reconnect_ms = get_now_ms() + RECONNECT_INTERVAL_MS;
        return;
    }
    if (set_nonblocking(fd) != SC_OK) {
        close(fd);
        p->next_reconnect_ms = get_now_ms() + RECONNECT_INTERVAL_MS;
        return;
    }

    memset(&sa, 0, sizeof sa);
    sa.sin_family = AF_INET;
    sa.sin_port   = htons(p->port);
    if (inet_pton(AF_INET, p->host, &sa.sin_addr) != 1) {
        close(fd);
        p->next_reconnect_ms = get_now_ms() + RECONNECT_INTERVAL_MS;
        return;
    }

    p->fd      = fd;
    p->state   = PEER_CONNECTING;
    p->in_len  = 0;
    p->out_len = 0;

    int rc = connect(fd, (struct sockaddr *)&sa, sizeof sa);
    if (rc == 0) {
        /* Instant connect (loopback) */
        log_eventf(LOG_DEBUG, "net", "tcp_connected", "peer=%d dir=outbound", p->node_id);
        send_hello_init(net, p);
    } else if (errno == EINPROGRESS) {
        /* Non-blocking connect in progress; handle in POLLOUT */
    } else {
        close(fd);
        p->fd    = -1;
        p->state = PEER_DISCONNECTED;
        p->next_reconnect_ms = get_now_ms() + RECONNECT_INTERVAL_MS;
    }
}

/* ------------------------------------------------------------------ */
/* Public API                                                          */
/* ------------------------------------------------------------------ */

sc_err_t net_init(sc_net_t **net_out, const network_config_t *topology,
                  const node_info_t *me, int listen_fd,
                  const sc_keypair_t *my_keypair,
                  sc_net_msg_cb msg_cb, void *user,
                  char *errbuf, size_t errlen)
{
    (void)errbuf; (void)errlen;

    sc_net_t *net = calloc(1, sizeof(*net));
    if (!net)
        return SC_ERR_IO;

    net->me         = me;
    net->my_keypair = my_keypair;
    net->topology   = topology;
    net->listen_fd  = listen_fd;
    net->msg_cb     = msg_cb;
    net->user_data  = user;

    set_nonblocking(listen_fd);

    size_t pcount = 0;
    for (size_t i = 0; i < topology->count; i++) {
        const node_info_t *ni = &topology->nodes[i];
        if (ni->id == me->id)
            continue;

        peer_conn_t *p = &net->peers[pcount++];
        p->node_id  = ni->id;
        snprintf(p->host, sizeof(p->host), "%s", ni->host);
        p->port     = ni->port;
        p->fd       = -1;
        p->state    = PEER_DISCONNECTED;
        /* Lower-id node initiates to higher-id; avoids duplicate connections. */
        p->is_target = (me->id < ni->id);
        p->next_reconnect_ms = 0;
    }
    net->peer_count = pcount;

    for (int i = 0; i < MAX_PENDING_INBOUND; i++) {
        net->pending[i].fd = -1;
        net->pending[i].hs_state = PEND_WAIT_INIT;
    }

    *net_out = net;
    return SC_OK;
}

void net_shutdown(sc_net_t *net)
{
    if (!net)
        return;
    for (size_t i = 0; i < net->peer_count; i++) {
        if (net->peers[i].fd >= 0) {
            close(net->peers[i].fd);
            net->peers[i].fd = -1;
        }
    }
    for (int i = 0; i < MAX_PENDING_INBOUND; i++) {
        if (net->pending[i].fd >= 0) {
            close(net->pending[i].fd);
            net->pending[i].fd = -1;
        }
    }
    free(net);
}

sc_err_t net_send(sc_net_t *net, int target_node_id, uint16_t type,
                  const void *payload, size_t len)
{
    if (!net)
        return SC_ERR_INVALID;
    if (len > SC_NET_MAX_PAYLOAD)
        return SC_ERR_INVALID;

    if (target_node_id == SC_BROADCAST_ALL) {
        for (size_t i = 0; i < net->peer_count; i++) {
            peer_conn_t *p = &net->peers[i];
            if (p->state == PEER_CONNECTED)
                enqueue_to_peer(p, type, payload, len);
        }
        return SC_OK;
    }

    peer_conn_t *p = find_peer_by_id(net, target_node_id);
    if (!p)
        return SC_ERR_NOT_FOUND;
    if (p->state != PEER_CONNECTED)
        return SC_ERR_IO;

    return enqueue_to_peer(p, type, payload, len) ? SC_OK : SC_ERR_IO;
}

bool net_is_connected(const sc_net_t *net, int target_node_id)
{
    if (!net)
        return false;
    for (size_t i = 0; i < net->peer_count; i++) {
        if (net->peers[i].node_id == target_node_id)
            return net->peers[i].state == PEER_CONNECTED;
    }
    return false;
}

size_t net_connected_count(const sc_net_t *net)
{
    if (!net)
        return 0;
    size_t count = 0;
    for (size_t i = 0; i < net->peer_count; i++) {
        if (net->peers[i].state == PEER_CONNECTED)
            count++;
    }
    return count;
}

sc_err_t net_poll_step(sc_net_t *net, int timeout_ms)
{
    if (!net)
        return SC_ERR_INVALID;

    int64_t now_ms = get_now_ms();

    /* Attempt reconnects for outbound-target peers */
    for (size_t i = 0; i < net->peer_count; i++) {
        peer_conn_t *p = &net->peers[i];
        if (p->is_target && p->state == PEER_DISCONNECTED &&
            now_ms >= p->next_reconnect_ms) {
            start_connect(net, p);
        }
    }

    /* Build poll() fd set.
     * We have: 1 listen fd + up to SC_MAX_NODES peer fds
     *                      + up to MAX_PENDING_INBOUND pending fds */
    struct pollfd fds[1 + SC_MAX_NODES + MAX_PENDING_INBOUND];
    int  fd_map_type[1 + SC_MAX_NODES + MAX_PENDING_INBOUND]; /* 0=listen,1=peer,2=pend */
    size_t fd_map_idx[1 + SC_MAX_NODES + MAX_PENDING_INBOUND];
    nfds_t nfds = 0;

    /* Listen socket: watch for incoming connections */
    fds[nfds].fd      = net->listen_fd;
    fds[nfds].events  = POLLIN;
    fds[nfds].revents = 0;
    fd_map_type[nfds] = 0;
    fd_map_idx[nfds]  = 0;
    nfds++;

    /* Established / in-handshake peer sockets */
    for (size_t i = 0; i < net->peer_count; i++) {
        peer_conn_t *p = &net->peers[i];
        if (p->fd < 0)
            continue;
        fds[nfds].fd      = p->fd;
        fds[nfds].events  = POLLIN;
        /* Need POLLOUT if: async connect still pending OR we have data to send */
        if (p->state == PEER_CONNECTING || p->out_len > 0)
            fds[nfds].events |= POLLOUT;
        fds[nfds].revents = 0;
        fd_map_type[nfds] = 1;
        fd_map_idx[nfds]  = i;
        nfds++;
    }

    /* Pending inbound sockets (still in handshake) */
    for (size_t i = 0; i < MAX_PENDING_INBOUND; i++) {
        pending_conn_t *pend = &net->pending[i];
        if (pend->fd < 0)
            continue;
        fds[nfds].fd      = pend->fd;
        fds[nfds].events  = POLLIN;
        if (pend->out_len > 0)
            fds[nfds].events |= POLLOUT;
        fds[nfds].revents = 0;
        fd_map_type[nfds] = 2;
        fd_map_idx[nfds]  = i;
        nfds++;
    }

    int poll_rc = poll(fds, nfds, timeout_ms);
    if (poll_rc < 0) {
        if (errno == EINTR)
            return SC_OK;
        return SC_ERR_IO;
    }
    if (poll_rc == 0)
        return SC_OK;

    for (nfds_t i = 0; i < nfds; i++) {
        if (fds[i].revents == 0)
            continue;
        short rev = fds[i].revents;

        /* ---- Listen socket: accept new inbound connections ---- */
        if (fd_map_type[i] == 0) {
            if (!(rev & POLLIN))
                continue;
            struct sockaddr_in csa;
            socklen_t clen = sizeof(csa);
            int cfd = accept(net->listen_fd, (struct sockaddr *)&csa, &clen);
            if (cfd < 0)
                continue;
            set_nonblocking(cfd);
            /* Find a free pending slot */
            int slot = -1;
            for (int k = 0; k < MAX_PENDING_INBOUND; k++) {
                if (net->pending[k].fd < 0) { slot = k; break; }
            }
            if (slot >= 0) {
                net->pending[slot].fd       = cfd;
                net->pending[slot].in_len   = 0;
                net->pending[slot].out_len  = 0;
                net->pending[slot].hs_state = PEND_WAIT_INIT;
            } else {
                close(cfd); /* no room — backpressure */
            }

        /* ---- Established/in-progress peer socket ---- */
        } else if (fd_map_type[i] == 1) {
            peer_conn_t *p = &net->peers[fd_map_idx[i]];

            /* Complete an async TCP connect */
            if (p->state == PEER_CONNECTING) {
                if (rev & (POLLOUT | POLLERR | POLLHUP)) {
                    int soerr = 0;
                    socklen_t elen = sizeof(soerr);
                    getsockopt(p->fd, SOL_SOCKET, SO_ERROR, &soerr, &elen);
                    if (soerr == 0) {
                        log_eventf(LOG_DEBUG, "net", "tcp_connected",
                                   "peer=%d dir=outbound", p->node_id);
                        send_hello_init(net, p);
                    } else {
                        close_peer(net, p, "connect failed");
                        continue;
                    }
                }
            }

            /* Flush outbound data */
            if ((rev & POLLOUT) && p->state != PEER_CONNECTING && p->out_len > 0) {
                if (!flush_pending_out(p->fd, p->out_buf, &p->out_len))
                    close_peer(net, p, "send error");
                continue; /* Re-evaluate next iteration */
            }

            /* Receive data */
            if (rev & (POLLIN | POLLHUP | POLLERR)) {
                if (p->state == PEER_CONNECTED ||
                    p->state == PEER_HS_INIT_SENT ||
                    p->state == PEER_HS_RESP_SENT) {
                    ssize_t n = recv(p->fd, p->in_buf + p->in_len,
                                     sizeof(p->in_buf) - p->in_len, 0);
                    if (n > 0) {
                        p->in_len += (size_t)n;
                        if (p->state == PEER_CONNECTED)
                            drain_peer_in_buf(net, p);
                        else if (p->state == PEER_HS_INIT_SENT) {
                            /* Expect HELLO_CHAL */
                            while (p->in_len >= SC_NET_HEADER_LEN) {
                                uint32_t net_len; uint16_t net_type;
                                memcpy(&net_len,  p->in_buf, 4);
                                memcpy(&net_type, p->in_buf + 4, 2);
                                uint32_t plen = ntohl(net_len);
                                uint16_t type = ntohs(net_type);
                                if (plen > SC_NET_MAX_PAYLOAD) {
                                    close_peer(net, p, "oversized"); break;
                                }
                                if (p->in_len < SC_NET_HEADER_LEN + plen) break;
                                if (type == MSG_TYPE_HELLO_CHAL) {
                                    handle_hello_chal(net, p,
                                        p->in_buf + SC_NET_HEADER_LEN, plen);
                                } else {
                                    close_peer(net, p, "expected HELLO_CHAL"); break;
                                }
                                size_t rem = p->in_len - (SC_NET_HEADER_LEN + plen);
                                if (rem) memmove(p->in_buf, p->in_buf + SC_NET_HEADER_LEN + plen, rem);
                                p->in_len = rem;
                                if (p->state != PEER_CONNECTED) break;
                            }
                        }
                    } else if (n == 0) {
                        close_peer(net, p, "peer closed");
                    } else if (errno != EAGAIN && errno != EWOULDBLOCK && errno != EINTR) {
                        close_peer(net, p, "recv error");
                    }
                }
            }

        /* ---- Pending inbound socket (pre-authentication) ---- */
        } else if (fd_map_type[i] == 2) {
            pending_conn_t *pend = &net->pending[fd_map_idx[i]];

            /* Send buffered data (HELLO_CHAL response) */
            if ((rev & POLLOUT) && pend->out_len > 0) {
                if (!flush_pending_out(pend->fd, pend->out_buf, &pend->out_len))
                    close_pending(pend);
            }

            /* Receive handshake bytes */
            if (pend->fd >= 0 && (rev & (POLLIN | POLLHUP | POLLERR))) {
                ssize_t n = recv(pend->fd, pend->in_buf + pend->in_len,
                                 sizeof(pend->in_buf) - pend->in_len, 0);
                if (n > 0) {
                    pend->in_len += (size_t)n;
                    drain_pending_in_buf(net, pend);
                } else if (n == 0 || (errno != EAGAIN && errno != EWOULDBLOCK && errno != EINTR)) {
                    close_pending(pend);
                }
            }
        }
    }

    return SC_OK;
}
